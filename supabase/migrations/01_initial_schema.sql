-- Initial schema for AquaGas Premium
-- Run this in Supabase SQL editor

-- Users table
create table if not exists users (
  id bigint generated by default as identity primary key,
  email text unique not null,
  password text,
  name text not null,
  role text not null check (role in ('admin', 'wholesale', 'retail')),
  phone text default '',
  address text default '',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Categories table
create table if not exists categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  icon text default 'Package',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Products table
create table if not exists products (
  id bigint generated by default as identity primary key,
  name text not null,
  category_id bigint not null references categories(id),
  retail_price numeric not null,
  wholesale_price numeric not null,
  stock integer not null default 0,
  min_wholesale_qty integer not null default 1,
  unit text default 'unit',
  status text default 'Tersedia' check (status in ('Tersedia', 'Menipis', 'Kosong')),
  image text default '',
  description text default '',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Orders table
create table if not exists orders (
  id bigint generated by default as identity primary key,
  order_number text unique not null,
  user_id bigint not null references users(id),
  status text default 'pending' check (status in ('pending', 'processing', 'completed', 'cancelled')),
  total_amount numeric not null,
  payment_method text default 'cod' check (payment_method in ('cod', 'transfer')),
  payment_status text default 'unpaid' check (payment_status in ('unpaid', 'paid', 'refunded')),
  notes text default '',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Order items table
create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id),
  product_id bigint not null references products(id),
  quantity integer not null,
  price numeric not null,
  subtotal numeric not null,
  created_at timestamp with time zone default now()
);

-- Refill suppliers table
create table if not exists refill_suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text default '',
  address text default '',
  contact_person text default '',
  is_active boolean default true,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Refill schedules table
create table if not exists refill_schedules (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references refill_suppliers(id),
  product_id bigint not null references products(id),
  schedule_date date not null,
  estimated_time text default '',
  quantity integer not null default 0,
  status text default 'direncanakan' check (status in ('direncanakan', 'dalam_perjalanan', 'selesai', 'dibatalkan')),
  notes text default '',
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now()
);

-- Settings table
create table if not exists settings (
  key text primary key,
  value text default ''
);

-- Guest visits table
create table if not exists guest_visits (
  id bigint generated by default as identity primary key,
  ip_address text default '',
  user_agent text default '',
  path text default '',
  visited_at timestamp with time zone default now()
);

