alter table products enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;
alter table refill_suppliers enable row level security;
alter table refill_schedules enable row level security;
alter table settings enable row level security;
alter table guest_visits enable row level security;

-- RLS Policies

-- Admin/service role can view all users (needed for login flow)
create policy "Admin can view all users"
  on users for select
  using (auth.jwt() ->> 'role' = 'admin' or auth.role() = 'service_role');

-- Admin can update users
create policy "Admin can update users"
  on users for update
  using (auth.jwt() ->> 'role' = 'admin' or auth.role() = 'service_role');

-- Everyone can view categories
create policy "Categories are public"
  on categories for select
  using (true);

-- Everyone can view available products
create policy "Products view for all"
  on products for select
  using (true);

-- Admin can manage products
create policy "Admin can manage products"
  on products for all
  using (auth.jwt() ->> 'role' = 'admin');

-- Users can view their own orders
create policy "Users can view own orders"
  on orders for select
  using (auth.uid()::text = (select email from users where id = user_id));

-- Admin can view all orders
create policy "Admin can view all orders"
  on orders for select
  using (auth.jwt() ->> 'role' = 'admin');

-- Everyone can view settings
create policy "Settings are public"
  on settings for select
  using (true);

